import { test, expect } from '@playwright/test'
async function session(page, role = 'agent') {
  await page.addInitScript(role => {
    localStorage.setItem('auth_token', 'test-token')
    localStorage.setItem('auth_role', role)
    localStorage.setItem('auth_user', JSON.stringify({ email:'alex@example.test' }))
    localStorage.setItem('passkey_prompt_dismissed:undefined', 'true')
  }, role)
  await page.route('**/api/admin/**', route => route.fulfill({ json:{ agents:[], cases:[], logs:[], entries:[], groupedByIp:[], activities:[], stats:{}, total:0 } }))
  await page.route('**/api/agent/audit', route => route.fulfill({ json:{ logs:[] } }))
}
async function noOverflow(page) {
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
test('login offers an icon-only passkey beside password sign-in on desktop and mobile', async ({ page }) => {
  await page.addInitScript(() => { PublicKeyCredential.isConditionalMediationAvailable = async () => false })
  await page.goto('/login')
  const button = page.getByRole('button', { name:'Sign in with a passkey' })
  await expect(button).toBeVisible()
  await expect(button).toHaveText('')
  expect(await button.getAttribute('type')).toBe('button')
  const submit = await page.getByRole('button', { name:'Sign In', exact:true }).boundingBox()
  const passkey = await button.boundingBox()
  expect(Math.abs(submit.y-passkey.y)).toBeLessThan(3)
  await page.screenshot({ path:'test-results/login-desktop.png', fullPage:true, animations:'disabled' })
  await page.setViewportSize({ width:390, height:844 })
  await noOverflow(page)
  await page.screenshot({ path:'test-results/login-mobile.png', fullPage:true, animations:'disabled' })
})
test('agent sidebar collapses, persists and navigates; mobile drawer closes on escape', async ({ page }) => {
  await session(page)
  await page.goto('/agent/platform')
  await expect(page.getByRole('navigation', { name:'Main navigation' })).toBeVisible()
  await page.screenshot({ path:'test-results/agent-desktop.png', fullPage:true, animations:'disabled' })
  await page.getByRole('button', { name:'Collapse sidebar' }).click()
  await expect(page.locator('.app-shell')).toHaveClass(/is-collapsed/)
  await page.reload()
  await expect(page.getByRole('button', { name:'Expand sidebar' })).toBeVisible()
  await page.getByRole('button', { name:'Expand sidebar' }).click()
  await page.getByRole('link', { name:'Activity history', exact:true }).click()
  await expect(page).toHaveURL(/agent\/audit/)
  await page.setViewportSize({ width:390, height:844 })
  await noOverflow(page)
  await page.getByRole('button', { name:'Open navigation' }).click()
  await expect(page.locator('.app-shell')).toHaveClass(/menu-open/)
  await page.screenshot({ path:'test-results/navigation-mobile.png', fullPage:true, animations:'disabled' })
  await page.keyboard.press('Escape')
  await expect(page.locator('.app-shell')).not.toHaveClass(/menu-open/)
})
test('admin sidebar selects views and restores selection after refresh', async ({ page }) => {
  await session(page, 'admin')
  await page.goto('/admin/dashboard')
  await page.screenshot({ path:'test-results/admin-desktop.png', fullPage:true, animations:'disabled' })
  await page.getByRole('link', { name:'Review queue', exact:true }).click()
  await expect(page).toHaveURL(/view=pending/)
  await expect(page.locator('#pending-section')).toBeVisible()
  await page.reload()
  await expect(page.locator('#pending-section')).toBeVisible()
  await page.getByRole('link', { name:'Flagged registrations', exact:true }).click()
  await expect(page.getByRole('link', { name:'Flagged registrations', exact:true })).toHaveAttribute('aria-current','page')
  await page.setViewportSize({ width:390, height:844 })
  await noOverflow(page)
})

test('all entry and workspace views fit desktop and mobile screens', async ({ page }) => {
  for (const path of ['/register','/check-email','/pending']) {
    await page.goto(path)
    await page.setViewportSize({ width:390, height:844 })
    await noOverflow(page)
    await expect(page.locator('h1')).toBeVisible()
  }
  await session(page)
  for (const path of ['/complete-profile','/agent/dashboard','/agent/passkeys','/agent/platform']) {
    await page.goto(path)
    await expect(page.locator('h1')).toBeVisible()
    await noOverflow(page)
    await page.screenshot({ path:`test-results/${path.split('/').pop()}-mobile.png`, fullPage:true, animations:'disabled' })
    await page.setViewportSize({ width:1440, height:900 })
    await noOverflow(page)
    await page.screenshot({ path:`test-results/${path.split('/').pop()}-desktop.png`, fullPage:true, animations:'disabled' })
    await page.setViewportSize({ width:390, height:844 })
  }
  await session(page, 'admin')
  await page.route('**/api/admin/model/evaluation', route => route.fulfill({ json:{ accuracy:0.95, confusion_matrix:[[90,3,1],[2,40,3],[1,2,50]] } }))
  await page.goto('/admin/model')
  await noOverflow(page)
  await page.screenshot({ path:'test-results/model-mobile.png', fullPage:true, animations:'disabled' })
  await expect(page.getByRole('heading', { name:'Model Evaluation' })).toBeVisible()
})
